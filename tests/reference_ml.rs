fn data() -> Vec<Vec<f64>> {
    DATA.iter().map(|r| r.to_vec()).collect()
}

fn close(got: f64, want: f64, rel: f64, what: &str) {
    let scale = want.abs().max(1e-12);
    assert!(
        (got - want).abs() <= rel * scale,
        "{what}: got {got}, want {want}"
    );
}

/// Two labelings name the same partition when equal labels coincide.
fn same_partition(a: &[usize], b: &[usize]) -> bool {
    a.len() == b.len()
        && (0..a.len()).all(|i| (0..a.len()).all(|j| (a[i] == a[j]) == (b[i] == b[j])))
}

#[test]
fn silhouette_matches_scikit_learn() {
    let labels = SIL_LABELS.to_vec();
    close(
        silhouette_score(&data(), &labels, 3),
        SIL_AVG,
        1e-10,
        "mean silhouette",
    );
    let s = silhouette_samples(&data(), &labels, 3);
    close(s.avg, SIL_AVG, 1e-10, "analysis mean");
    for i in 0..N {
        close(
            s.per_sample[i],
            SIL_SAMPLES[i],
            1e-9,
            &format!("sample {i}"),
        );
    }
}

#[test]
fn pca_matches_scikit_learn_and_the_correlation_eigenvalues() {
    let r = pca(&data(), &PcaConfig::new(3)).unwrap();
    for c in 0..3 {
        close(
            r.eigenvalues[c],
            PCA_EIG[c],
            1e-9,
            &format!("eigenvalue {c}"),
        );
        close(
            r.explained_variance_ratio[c],
            PCA_RATIO[c],
            1e-9,
            &format!("ratio {c}"),
        );
        // a component's sign is arbitrary: compare the magnitudes
        for f in 0..D {
            close(
                r.loadings[c][f].abs().max(1e-12),
                PCA_COMP_ABS[c][f].max(1e-12),
                1e-6,
                &format!("loading {c},{f}"),
            );
        }
        for i in 0..N {
            close(
                r.scores[i][c].abs().max(1e-9),
                PCA_SCORES_ABS[i][c].max(1e-9),
                1e-6,
                &format!("score {i},{c}"),
            );
        }
    }
    let scaled = pca(&data(), &PcaConfig::new(3).auto_scale(true)).unwrap();
    for c in 0..3 {
        close(
            scaled.eigenvalues[c],
            PCA_CORR_EIG[c],
            1e-9,
            &format!("correlation eigenvalue {c}"),
        );
    }
}

#[test]
fn dbscan_matches_scikit_learn() {
    let r = dbscan(&data(), &DbscanConfig::new(1.4, 4)).unwrap();
    let noise: Vec<bool> = DB_LABELS.iter().map(|&l| l < 0).collect();
    for i in 0..N {
        assert_eq!(r.labels[i].is_none(), noise[i], "noise {i}");
        assert_eq!(r.core_points[i], DB_CORE[i], "core {i}");
        // both number clusters by first appearance
        assert_eq!(
            r.labels[i].map(|l| l as i64).unwrap_or(-1),
            DB_LABELS[i],
            "label {i}"
        );
    }
}

#[test]
fn hierarchical_merge_heights_and_cuts_match_scipy() {
    let cases = [
        (Linkage::Ward, HC_WARD_HEIGHTS, HC_WARD_CUT3),
        (Linkage::Single, HC_SINGLE_HEIGHTS, HC_SINGLE_CUT3),
        (Linkage::Complete, HC_COMPLETE_HEIGHTS, HC_COMPLETE_CUT3),
        (Linkage::Average, HC_AVERAGE_HEIGHTS, HC_AVERAGE_CUT3),
    ];
    for (linkage, heights, cut) in cases {
        let r = hierarchical(&data(), &HierarchicalConfig::with_k(3).linkage(linkage)).unwrap();
        assert_eq!(r.merges.len(), N - 1, "{linkage:?}");
        for (i, m) in r.merges.iter().enumerate() {
            close(
                m.distance,
                heights[i],
                1e-9,
                &format!("{linkage:?} merge {i}"),
            );
        }
        let labels = r.labels.expect("cut into 3");
        assert!(
            same_partition(&labels, &cut),
            "{linkage:?}: cut into 3 differs"
        );
    }
}

