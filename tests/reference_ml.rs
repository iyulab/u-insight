/// Well-separated blobs have one global optimum; scikit-learn's best of ten
/// restarts and this crate's best of ten find it, so inertia and partition agree.
#[test]
fn kmeans_finds_the_same_optimum_as_scikit_learn() {
    let r = kmeans(&data(), &KMeansConfig::new(3)).unwrap();
    close(r.wcss, KM_INERTIA, 1e-9, "inertia");
    assert!(same_partition(&r.labels, &KM_LABELS), "partition differs");
}
